from odoo import Command, _, api, fields, models
from odoo.tools import human_size

# Stored in ir.attachment.description to recognize the invoice PDFs this
# module adds to a composer.
PAYMENT_INVOICE_MARKER = "account_payment_email_invoices"


def _unique_name(name, taken):
    """Return ``name``, or ``name`` with a " (n)" suffix before its extension,
    so that it does not clash with any name of ``taken`` (case-insensitive).
    ``taken`` is updated with the returned name."""
    stem, dot, extension = name.rpartition(".")
    if not dot:
        stem, extension = name, ""
    candidate, counter = name, 1
    while candidate.lower() in taken:
        counter += 1
        candidate = f"{stem} ({counter}){dot}{extension}"
    taken.add(candidate.lower())
    return candidate


def _attachment_ids_from_values(values):
    """IDs of the attachments given as ``attachment_ids`` in mail values,
    either plain IDs (comment mode) or link commands (mass mail mode)."""
    ids = []
    for item in values or []:
        if isinstance(item, int):
            ids.append(item)
        elif isinstance(item, (list, tuple)) and item and item[0] == Command.LINK:
            ids.append(item[1])
        elif isinstance(item, (list, tuple)) and item and item[0] == Command.SET:
            ids.extend(item[2])
    return ids


class MailComposeMessage(models.TransientModel):
    _inherit = "mail.compose.message"

    payment_attachment_size_warning = fields.Text(
        string="Attachment size warning",
        compute="_compute_payment_attachment_size_warning",
    )

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _payment_invoices_template_applies(self):
        """Invoices are only added to emails of payments that send the payment
        receipt (payment order / receipt) report."""
        self.ensure_one()
        if self.model != "account.payment" or not self.template_id:
            return False
        receipt_report = self.env.ref("account.action_report_payment_receipt", raise_if_not_found=False)
        return bool(receipt_report) and receipt_report in self.template_id.sudo().report_template_ids

    def _get_payment_invoice_files(self, payment, taken_names):
        """Return [(file name, PDF content)] of the documents to attach to the
        email of ``payment``, with names unique among ``taken_names``."""
        invoices = payment._get_email_invoices()
        if not invoices:
            return []
        pdfs = invoices._get_payment_email_pdfs()
        taken = {name.lower() for name in taken_names if name}
        return [
            (_unique_name(move._get_payment_email_attachment_name(), taken), pdfs[move])
            for move in invoices
            if pdfs.get(move)
        ]

    def _payments_for_invoices(self, res_ids):
        # Documents are read as the current user, never as superuser (the
        # stored compute of attachment_ids runs as superuser).
        return self.env(su=False)["account.payment"].browse(res_ids)

    # ------------------------------------------------------------------
    # Preview (monorecord comment mode)
    # ------------------------------------------------------------------

    def _compute_attachment_ids(self):
        """Add the documents' PDFs after the attachments of the template, so
        that the user sees them before sending and can remove them. They are
        temporary composer attachments (res_model mail.compose.message,
        res_id 0), like the reports generated by the template: the posting
        process moves them to the payment, and the ones never sent are garbage
        collected (mail.compose.message._gc_lost_attachments)."""
        super()._compute_attachment_ids()
        for composer in self:
            if composer.composition_mode != "comment" or composer.composition_batch:
                continue
            res_ids = composer._evaluate_res_ids()
            if len(res_ids) != 1 or not composer._payment_invoices_template_applies():
                continue
            payment = composer._payments_for_invoices(res_ids)
            files = composer._get_payment_invoice_files(payment, composer.attachment_ids.mapped("name"))
            if not files:
                continue
            attachments = self.env(su=False)["ir.attachment"].create(
                [
                    {
                        "name": name,
                        "raw": content,
                        "mimetype": "application/pdf",
                        "res_model": "mail.compose.message",
                        "res_id": 0,
                        "type": "binary",
                        "description": PAYMENT_INVOICE_MARKER,
                    }
                    for name, content in files
                ]
            )
            composer.attachment_ids = [Command.link(attachment.id) for attachment in attachments]

    @api.depends("attachment_ids", "body", "template_id", "model", "res_ids", "composition_mode", "mail_server_id")
    def _compute_payment_attachment_size_warning(self):
        """Warn when the attachments exceed the size limit of the outgoing
        mail server. Nothing is removed: the user decides what to do."""
        for composer in self:
            composer.payment_attachment_size_warning = False
            if composer.composition_mode != "comment" or composer.composition_batch:
                continue
            res_ids = composer._evaluate_res_ids()
            if len(res_ids) != 1 or not composer._payment_invoices_template_applies():
                continue
            if not composer._payments_for_invoices(res_ids)._email_invoices_enabled():
                continue
            # Same estimation and limit as mail.mail._prepare_outgoing_list.
            estimated_size = self.env["mail.mail"]._estimate_email_size(
                {}, composer.body, composer.attachment_ids.sudo().mapped("file_size")
            )
            mail_server = composer.mail_server_id or composer.template_id.sudo().mail_server_id
            if not mail_server and composer.email_from:
                mail_server = self.env["ir.mail_server"].sudo()._find_mail_server(composer.email_from)[0]
            max_size = (mail_server or self.env["ir.mail_server"]).sudo()._get_max_email_size() * 1024 * 1024
            if estimated_size > max_size:
                composer.payment_attachment_size_warning = _(
                    "The attachments of this email add up to %(total)s, above the %(limit)s limit of "
                    "the outgoing mail server. If the email is sent as it is, Odoo replaces its "
                    "attachments with download links in the email body. Remove some attachments if "
                    "you want them to travel as files.",
                    total=human_size(estimated_size),
                    limit=human_size(max_size),
                )

    # ------------------------------------------------------------------
    # Sending (all modes)
    # ------------------------------------------------------------------

    def _manage_mail_values(self, mail_values_all):
        """Runs after every _prepare_mail_values override (e.g. the
        withholding certificates of l10n_ar_tax), so the documents' PDFs end
        up after every other attachment, in every sending flow: composer,
        mass mailing, message_post_with_source and scheduled messages."""
        mail_values_all = super()._manage_mail_values(mail_values_all)
        if not mail_values_all or not self._payment_invoices_template_applies():
            return mail_values_all
        if self.composition_mode == "mass_mail" or self.composition_batch:
            self._add_payment_invoices_to_rendered_values(mail_values_all)
        else:
            self._move_payment_invoices_last(mail_values_all)
        return mail_values_all

    def _add_payment_invoices_to_rendered_values(self, mail_values_all):
        """Rendering modes (mass mail, batch comment) have no preview: the
        documents are generated at sending time, for each payment."""
        email_mode = self.composition_mode == "mass_mail"
        attachment_model = self.env["ir.attachment"].sudo()
        for payment in self._payments_for_invoices(list(mail_values_all)):
            values = mail_values_all[payment.id]
            existing_ids = _attachment_ids_from_values(values.get("attachment_ids"))
            taken_names = attachment_model.browse(existing_ids).mapped("name")
            taken_names += [item[0] for item in values.get("attachments") or []]
            files = self._get_payment_invoice_files(payment, taken_names)
            if not files:
                continue
            if email_mode:
                # Same processing as _prepare_mail_values_dynamic does for the
                # template reports.
                link_to_record = not (self.auto_delete and not self.auto_delete_keep_log)
                commands = payment._process_attachments_for_post(
                    files, [], {} if link_to_record else {"model": "mail.message", "res_id": 0}
                )["attachment_ids"]
                values["attachment_ids"] = list(values.get("attachment_ids") or []) + commands
            else:
                # Created by message_post, after the other attachments.
                values["attachments"] = list(values.get("attachments") or []) + files

    def _move_payment_invoices_last(self, mail_values_all):
        """Monorecord comment mode: the PDFs were added in the preview, but an
        attachment added afterwards (by another module or by the user) has a
        higher ID, and emails list their attachments by ID. Copy the PDFs so
        that they come last, as specified, and drop the previous copies."""
        attachment_model = self.env["ir.attachment"]
        for values in mail_values_all.values():
            attachment_ids = values.get("attachment_ids") or []
            if not attachment_ids or not all(isinstance(item, int) for item in attachment_ids):
                continue
            attachments = attachment_model.browse(attachment_ids)
            ours = attachments.filtered(
                lambda a: a.description == PAYMENT_INVOICE_MARKER
                and a.res_model == "mail.compose.message"
                and not a.res_id
            )
            others = attachments - ours
            if not ours or not others or max(others.ids) < min(ours.ids):
                continue
            copies = attachment_model
            for attachment in ours.sorted("id"):
                copies |= attachment.copy({"res_model": "mail.compose.message", "res_id": 0})
            values["attachment_ids"] = [item for item in attachment_ids if item not in ours.ids] + copies.ids
            self.attachment_ids = [Command.unlink(a.id) for a in ours] + [Command.link(c.id) for c in copies]
            ours.unlink()
